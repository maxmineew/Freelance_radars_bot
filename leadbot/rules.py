"""Второй, дешёвый префильтр перед LLM: явная реклама, вакансии и «ищу работу» отсеиваем правилами.
Правило сработает только если в тексте нет явного запроса исполнителя («ищу разработчика бота»)."""
import re

DIRECT = re.compile(r"(?:ищу|ищем|нужен|нужна|нужны|требуется|требуются|посоветуйте|порекомендуйте).{0,100}"
                    r"(?:исполнител|подрядчик|разработчик|специалист|бот|обзвон|агент|автоматизац|интеграци)", re.I | re.S)
SEEKER = re.compile(r"ищу работу|ищу подработк|мо[её] резюме|предлагаю (?:свои )?услуги|возьмусь за|"
                    r"выполню (?:заказ|работ)|готов (?:взять|выполнить) (?:заказ|проект)", re.I)
VACANCY = re.compile(r"вакансия|оклад\b|\bз/п\b|график 5/2|в штат\b|официальн\w{0,10} оформлен|трудоустройств", re.I)
ADVERT = re.compile(r"подписывайтесь|подпишись на|скидк\w{1,3} до|\bакци[яи]\b|по промокоду|регистрируйтесь на|"
                    r"бесплатн\w{2,4} (?:урок|вебинар|консультац)|закажите у нас|наши услуги|"
                    r"запишитесь на (?:консультац|демо)|разработаем для вас|создаём (?:ботов|сайты)", re.I)


def noise_reason(text, exchange=None):
    """Код причины отсева или None. Заказы бирж не трогаем: это всегда заказ."""
    if exchange or DIRECT.search(text):
        return None
    for code, pattern in (("seeker", SEEKER), ("vacancy", VACANCY), ("advert", ADVERT)):
        if pattern.search(text):
            return code
    return None
